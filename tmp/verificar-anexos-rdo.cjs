const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const backend = path.resolve('gestao-obras-vetor/backend');
const localRequire = require('node:module').createRequire(path.join(backend, 'package.json'));
localRequire('dotenv').config({path:path.join(backend,'.env')});
assert.ok(['localhost','127.0.0.1','::1'].includes(process.env.DB_HOST || 'localhost'));
const db=localRequire('./config/database');
const express=localRequire('express');
const puppeteer=localRequire('puppeteer');
const tenant=700000000+process.pid;
const uploadDir=path.join(backend,'uploads','tenant_'+tenant);
assert.equal(fs.existsSync(uploadDir),false);
(async()=>{
  const client=await db.pool.connect();
  let server,browser;
  try {
    await client.query('BEGIN');
    await client.query('CREATE TEMP TABLE anexos(id serial primary key,rdo_id integer,tenant_id bigint,rnc_id integer,tipo text,nome_arquivo text,caminho_arquivo text,tamanho integer,descricao text,criado_por integer,criado_em timestamptz default now())');
    await client.query('CREATE TEMP TABLE usuarios(id integer,nome text)');
    await client.query('SET LOCAL search_path TO pg_temp');
    Object.assign(db,{allQuery:(sql,p)=>db.allWithClient(client,sql,p),getQuery:(sql,p)=>db.getWithClient(client,sql,p),runQuery:(sql,p)=>db.execWithClient(client,sql,p)});
    localRequire('./middleware/auth').auth=(req,res,next)=>{req.usuario={id:1};req.tenantId=tenant;next()};
    const app=express();
    app.use(express.json());
    const report={id:29,numero_rdo:14,status:'Em preenchimento',data_relatorio:'2026-11-17',sem_ocorrencias:true,atividades:[],ocorrencias:[]};
    let uploads=0,creates=0,failList=false,failEmbedded=false;
    app.post('/api/rdos',(req,res)=>{creates++;res.status(201).json({rdo:{id:29}})});
    app.put('/api/rdos/29',(req,res)=>res.json({}));
    const rows=()=>db.allQuery('select * from anexos where rdo_id=? and rnc_id is null order by id desc',[29]);
    app.get('/api/rdos/29',async(req,res)=>res.json({...report,anexos:failEmbedded?null:await rows()}));
    app.get('/api/anexos/rdo/29',(req,res,next)=>failList?res.sendStatus(503):next());
    app.post('/api/anexos/upload/:id',(req,res,next)=>{assert.equal(req.params.id,'29');if(++uploads===2)return res.status(503).json({erro:'Indisponibilidade de teste'});next()});
    app.use('/api/anexos',localRequire('./routes/anexos'));
    app.use('/api/uploads',localRequire('./routes/uploads'));
    app.use('/api',(req,res)=>res.json([]));
    const dist=path.resolve('gestao-obras-vetor/frontend/dist');
    app.use(express.static(dist));
    app.get('*',(req,res)=>res.sendFile(path.join(dist,'index.html')));
    server=app.listen(0,'127.0.0.1');
    await new Promise(r=>server.once('listening',r));
    const origin='http://127.0.0.1:'+server.address().port;
    browser=await puppeteer.launch({headless:true,executablePath:'C:/Program Files/Google/Chrome/Application/chrome.exe'});
    const page=await browser.newPage();
    page.setDefaultTimeout(10000);
    const errors=[];
    page.on('pageerror',e=>{errors.push(e.message);console.error(e.message)});
    page.on('dialog',d=>d.accept());
    await page.evaluateOnNewDocument(()=>{localStorage.setItem('app_version','3');localStorage.setItem('token','fixture');localStorage.setItem('usuario',JSON.stringify({id:1,nome:'Teste',perfil:'Gestor Geral',tenant_id:1}))});
    await page.goto(origin+'/projeto/1/rdos/novo');
    await page.waitForSelector('input[type=date]');
    await page.$eval('input[type=date]',el=>{Object.getOwnPropertyDescriptor(HTMLInputElement.prototype,'value').set.call(el,'2026-11-17');el.dispatchEvent(new Event('input',{bubbles:true}))});
    const selectFiles=async(names)=>page.$eval('input[accept^=".pdf"]',(el,names)=>{const data=new DataTransfer();names.forEach(n=>data.items.add(new File(['conteudo-teste'],n,{type:n.endsWith('.pdf')?'application/pdf':'image/png'})));el.files=data.files;el.dispatchEvent(new Event('change',{bubbles:true}))},names);
    const save=async()=>{await page.click('[aria-label="Opções do RDO"]');await page.waitForFunction(()=>Array.from(document.querySelectorAll('.rdo-actions-menu-item')).some(b=>b.textContent.trim()==='Salvar RDO'&&!b.disabled));await page.evaluate(()=>Array.from(document.querySelectorAll('.rdo-actions-menu-item')).find(b=>b.textContent.trim()==='Salvar RDO').click())};
    await selectFiles(['planta.pdf','desenho.png']);
    await save();
    await page.waitForFunction(()=>document.body.textContent.includes('Indisponibilidade de teste'));
    assert.equal((await rows()).length,1);
    await page.waitForFunction(()=>document.querySelector('input[type=date]').disabled);
    await save();
    await page.waitForFunction(()=>location.pathname.endsWith('/29/editar'));
    assert.equal(creates,1);assert.equal(uploads,3);assert.equal((await rows()).length,2);
    await page.waitForSelector('input[accept^=".pdf"]');
    await selectFiles(['memorial.pdf']);
    await page.waitForFunction(()=>Array.from(document.querySelectorAll('.rdo-anexo-item a')).length===3);
    await page.goto(origin+'/projeto/1/rdo/29');
    await page.waitForSelector('.rdo-report-attachment-card');
    const cards=await page.$$eval('.rdo-report-attachment-card',els=>els.map(e=>({name:e.querySelector('strong').textContent,url:e.href})));
    assert.deepEqual(cards.map(c=>c.name).sort(),['desenho.png','memorial.pdf','planta.pdf']);
    for(const card of cards) assert.equal(await(await fetch(card.url)).text(),'conteudo-teste');
    failList=true;
    await page.reload();await page.waitForSelector('.rdo-report-attachment-card');
    assert.equal((await page.$$('.rdo-report-attachment-card')).length,3);
    failEmbedded=true;await page.reload();await page.waitForSelector('.rdo-report-empty[role=alert]');
    failList=false;await page.click('.rdo-report-empty[role=alert] button');await page.waitForSelector('.rdo-report-attachment-card');
    assert.equal((await page.$$('.rdo-report-attachment-card')).length,3);
    assert.deepEqual(errors,[]);
    console.log('OK: criação com falha parcial, reenvio sem duplicação, edição, visualização, abertura dos três arquivos, falha de leitura e recuperação.');
  } finally {
    if(browser)await browser.close();if(server)server.close();
    await client.query('ROLLBACK');client.release();await db.pool.end();
    if(fs.existsSync(uploadDir)){for(const name of fs.readdirSync(uploadDir))fs.unlinkSync(path.join(uploadDir,name));fs.rmdirSync(uploadDir)}
  }
})().catch(e=>{console.error(e);process.exitCode=1});
