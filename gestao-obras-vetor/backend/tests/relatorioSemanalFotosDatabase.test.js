// Count paint instructions in PDFKit page streams, excluding the recurring brand (I1).
function paintedPhotos(bytes) {
  let count = 0;
  const raw = bytes.toString('latin1');
  for (const match of raw.matchAll(/<<\s*\/Length (\d+)\s*\/Filter \/FlateDecode\s*>>\s*stream\r?\n/g)) {
    const start = match.index + match[0].length;
    const content = zlib.inflateSync(bytes.subarray(start,start+Number(match[1]))).toString('latin1');
    for (const paint of content.matchAll(/\/I(\d+) Do\b/g)) if (paint[1] !== '1') count++;
  }
  return count;
}

